/**
 * Derives the parts of the API reference that drift when the library grows —
 * the indicator catalog and the drawing-tool list — straight from the core's
 * own source of truth, so the docs can't fall behind the code.
 *
 *   - Indicators come from `builtinIndicators` in `@lightfin/core/chrome` (the
 *     same map that builds the indicators menu). Each entry carries its menu
 *     label and a loader; loading it yields the definition, whose `name`,
 *     `overlay`/`scale`, and `defaultOptions` describe the indicator.
 *   - Drawing tools come from the `TOOLS` registry in the annotations package,
 *     whose `points` field is the number of points each tool takes.
 *   - Theme variables come from the `ChartTheme` interface in the core's
 *     options module: field names and types + per-field JSDoc are read with the
 *     TypeScript compiler API, and the default value of each is read from the
 *     `DEFAULT_THEME` runtime object. So the Theming guide's table can't drift.
 *
 * Output is three MDX partials under `src/generated/`, imported as components by
 * the hand-written reference pages. Run via `bun run gen` (the `dev`/`build`
 * scripts do this first); the result is committed so CI diffs catch drift.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import ts from 'typescript'

import { builtinIndicators } from '../../core/src/chrome/index'
import { TOOLS } from '../../core/src/annotations/tools'
import type { AnnotationType } from '../../core/src/annotations/types'
import { DEFAULT_THEME } from '../../core/src/chart/options'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = join(here, '..', 'src', 'generated')

const AUTOGEN =
  '{/* AUTO-GENERATED by scripts/gen-reference.ts — do not edit by hand. */}\n\n'

/** A default option worth showing: numbers/booleans, not palette colors. */
function isTuningOption(value: unknown): boolean {
  if (typeof value === 'number' || typeof value === 'boolean') return true
  if (typeof value !== 'string') return false
  // Colors come from the theme palette, not the catalog — skip them.
  return !/^(#|rgb|hsl)/i.test(value)
}

function formatDefaults(defaults: Record<string, unknown>): string {
  const pairs = Object.entries(defaults)
    .filter(([, v]) => isTuningOption(v))
    .map(([k, v]) => `\`${k}: ${JSON.stringify(v)}\``)
  return pairs.length ? pairs.join(', ') : '—'
}

function placementLabel(overlay: boolean, scale: unknown): string {
  if (!overlay) return 'Own pane'
  return scale === 'volume' ? 'Overlay (volume)' : 'Overlay (price)'
}

async function genIndicators(): Promise<void> {
  const rows: string[] = []
  for (const [id, entry] of Object.entries(builtinIndicators)) {
    const loaded = await entry.load()
    const def = 'default' in loaded ? loaded.default : loaded
    rows.push(
      `| ${entry.name} | \`${id}\` | ${def.name} | ${placementLabel(
        def.overlay,
        (def as { scale?: unknown }).scale,
      )} | ${formatDefaults(def.defaultOptions as Record<string, unknown>)} |`,
    )
  }
  const table = [
    '| Indicator | Subpath id | Legend | Placement | Default options |',
    '| --------- | ---------- | ------ | --------- | --------------- |',
    ...rows,
  ].join('\n')
  const body =
    AUTOGEN +
    table +
    `\n\nLoad any of them by its subpath id, e.g. ` +
    '`import(\'@lightfin/core/indicators/sma\')`. Colors are omitted above — ' +
    'each plot takes its color from `theme.indicatorPalette` unless you pass ' +
    'one in options.\n'
  await writeFile(join(outDir, 'indicators-catalog.mdx'), body)
  console.log(`indicators-catalog.mdx: ${rows.length} indicators`)
}

async function genTools(): Promise<void> {
  const rows = (Object.entries(TOOLS) as [AnnotationType, { points: number; freehand?: true }][]).map(
    ([type, spec]) =>
      `| \`${type}\` | ${spec.points}${spec.freehand ? ' or more' : ''} |`,
  )
  const table = [
    '| Tool (`type`) | Points |',
    '| ------------- | ------ |',
    ...rows,
  ].join('\n')
  const body =
    AUTOGEN +
    table +
    `\n\n${rows.length} tools. "Points" is how many anchors the tool takes; ` +
    'pass that many `{ time, price }` points to `add()`.\n'
  await writeFile(join(outDir, 'tools-catalog.mdx'), body)
  console.log(`tools-catalog.mdx: ${rows.length} tools`)
}

/** One cell's worth of a theme default, as inline code (lists for arrays). */
function formatThemeDefault(value: unknown): string {
  if (Array.isArray(value)) return value.map(v => `\`${v}\``).join(' ')
  if (typeof value === 'string') return `\`${value}\``
  return `\`${JSON.stringify(value)}\``
}

/** First JSDoc paragraph on a declaration, flattened to one line. */
function jsdocSummary(node: ts.Node): string {
  for (const part of ts.getJSDocCommentsAndTags(node)) {
    const comment = (part as ts.JSDoc).comment
    const text =
      typeof comment === 'string' ? comment : ts.getTextOfJSDocComment(comment)
    if (text)
      return text
        .replace(/\s+/g, ' ')
        .trim()
  }
  return '—'
}

/** Markdown-safe: escape pipes so a cell can't break out of the table. */
function cell(text: string): string {
  return text.replace(/\|/g, '\\|')
}

async function genTheme(): Promise<void> {
  const file = join(here, '..', '..', 'core', 'src', 'chart', 'options.ts')
  const source = ts.createSourceFile(
    file,
    await readFile(file, 'utf8'),
    ts.ScriptTarget.Latest,
    /* setParentNodes */ true,
  )

  const iface = source.statements.find(
    (s): s is ts.InterfaceDeclaration =>
      ts.isInterfaceDeclaration(s) && s.name.text === 'ChartTheme',
  )
  if (!iface) throw new Error('ChartTheme interface not found in options.ts')

  const rows: string[] = []
  for (const member of iface.members) {
    if (!ts.isPropertySignature(member) || !member.name) continue
    const name = member.name.getText(source)
    const type = member.type?.getText(source) ?? 'unknown'
    const def = formatThemeDefault(
      (DEFAULT_THEME as unknown as Record<string, unknown>)[name],
    )
    rows.push(
      `| \`${name}\` | \`${type}\` | ${def} | ${cell(jsdocSummary(member))} |`,
    )
  }

  const table = [
    '| Property | Type | Default | Description |',
    '| -------- | ---- | ------- | ----------- |',
    ...rows,
  ].join('\n')
  const body =
    AUTOGEN +
    table +
    `\n\n${rows.length} theme properties. Defaults are from \`DEFAULT_THEME\`; ` +
    'pass any subset as `theme` and the rest fall back to it.\n'
  await writeFile(join(outDir, 'theme-catalog.mdx'), body)
  console.log(`theme-catalog.mdx: ${rows.length} properties`)
}

await mkdir(outDir, { recursive: true })
await Promise.all([genIndicators(), genTools(), genTheme()])
